import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch
plt.rcParams.update({'font.family':'serif','font.serif':['DejaVu Serif'],'font.size':6.4})
fig,ax=plt.subplots(figsize=(5.6,5.0)); ax.set_xlim(-0.2,10.2); ax.set_ylim(-0.2,11.2); ax.axis('off')
def box(x,y,w,h,t,fc='#eef3fa'):
    ax.add_patch(FancyBboxPatch((x,y),w,h,boxstyle='round,pad=0.08',fc=fc,ec='#33475b',lw=.6)); ax.text(x+w/2,y+h/2,t,ha='center',va='center')
def arr(x1,y1,x2,y2): ax.annotate('',(x2,y2),(x1,y1),arrowprops=dict(arrowstyle='->',lw=.6,color='#33475b'))
box(2.3,10.0,5.4,0.95,'960 synthetic dialogues, 24 disease labels\n(MedicalConversations2Disease)','#f5f5f5')
arr(5,10.0,5,9.55)
box(0.3,8.1,9.4,1.35,'Seven text views: patient | bot | full, each with and without disease-name masking,\nplus masked full view length-matched to the patient view\nNormalization, stop-word + filler removal, lemmatization')
arr(2.6,8.1,2.4,7.45); arr(7.4,8.1,7.6,7.45)
box(0.1,5.9,4.6,1.45,'Bag-of-words / TF-IDF\nLDA, K-means, NMF, LSA, GloVe\nK = 5-40 (label-free K by silhouette)')
box(5.3,5.9,4.6,1.45,'Symptom extraction v2 (frozen)\n52-concept lexicon, ConText-style negation,\nelliptical replies, speaker attribution')
arr(2.4,5.9,2.4,5.25); arr(7.6,5.9,7.6,5.25)
box(0.1,3.7,4.6,1.45,'Supervised reference\nTF-IDF + logistic regression, nested CV\n(and 52-concept features)')
box(5.3,3.7,4.6,1.45,'Manual validation: 2 annotators\n120 dialogues (P/R/F1, kappa)\n+ 40 no-concept dialogues coded')
arr(7.6,3.7,7.6,3.05)
box(5.3,1.6,4.6,1.4,'Itemset-level Apriori: Fisher tests\n(Bonferroni, BH), bootstrap lift CIs,\ndisease-stratified MH odds ratios')
arr(2.4,3.7,2.4,1.25); arr(7.6,1.6,7.6,1.25)
box(0.3,-0.1,9.4,1.25,'Evaluation: AMI / ARI with dialogue-bootstrap CIs, paired view differences,\nMcNemar tests, threshold and preprocessing sensitivity','#fdf6e3')
plt.savefig('fig_pipeline_v3.png',dpi=400,bbox_inches='tight')
